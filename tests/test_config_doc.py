def test_get_and_has(tmp_path):
    d = _doc(tmp_path, "a:\n  b: [1, 2]\n")
    assert d.get(("a", "b", 0)) == 1
    assert d.get(("a", "b", -1)) == 2
    assert d.get(("a", "b", 5), "dflt") == "dflt"
    assert d.get(("a", "b", -5), "dflt") == "dflt"
    assert d.get(("a", 0), "x") == "x"          # int into a mapping
    assert d.get(("a", "b", "k"), "y") == "y"   # str into a list
    assert d.get(("zz",)) is None
    assert d.has(("a", "b"))
    assert not d.has(("a", "c"))


