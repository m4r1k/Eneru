def test_to_plain_types(tmp_path):
    d = _doc(tmp_path, "a:\n  i: 1\n  f: 1.5\n  b: true\n  n: null\n"
                       "  s: 'x'\n  l: [1, 'two']\n")
    plain = d.to_plain()
    assert plain == {"a": {"i": 1, "f": 1.5, "b": True, "n": None, "s": "x",
                           "l": [1, "two"]}}
    assert type(plain) is dict and type(plain["a"]) is dict
    assert type(plain["a"]["l"]) is list
    assert type(plain["a"]["i"]) is int and type(plain["a"]["f"]) is float
    assert type(plain["a"]["s"]) is str
    assert d.to_plain_at(("a", "l")) == [1, "two"]
    assert to_plain((1, 2)) == [1, 2]
    sentinel = object()
    assert to_plain(sentinel) is sentinel


