def test_save_existing_keeps_mode_and_writes_bak(tmp_path):
    p = tmp_path / "c.yaml"
    p.write_text("a: 1\n")
    os.chmod(p, 0o640)
    d = ConfigDocument.load(p)
    d.set(("a",), 2)
    d.save()
    assert p.read_text() == "a: 2\n"
    assert stat.S_IMODE(p.stat().st_mode) == 0o640
    bak = tmp_path / "c.yaml.bak"
    assert bak.read_text() == "a: 1\n"
    assert stat.S_IMODE(bak.stat().st_mode) == 0o600


def test_save_without_backup_and_to_other_path(tmp_path):
    p = tmp_path / "c.yaml"
    p.write_text("a: 1\n")
    d = ConfigDocument.load(p)
    other = tmp_path / "other.yaml"
    other.write_text("old: 1\n")
    assert d.save(other, backup=False) == other
    assert other.read_text() == "a: 1\n"
    assert not (tmp_path / "other.yaml.bak").exists()
    assert d.path == other


def test_save_failure_cleans_tmp(tmp_path):
    p = tmp_path / "c.yaml"
    p.write_text("a: 1\n")
    d = ConfigDocument.load(p)
    d.set(("a",), 2)
    with patch.object(cd.os, "replace", side_effect=OSError("disk full")):
        with pytest.raises(OSError):
            d.save(backup=False)
    leftovers = [f for f in os.listdir(tmp_path) if f.startswith(".c.yaml.")]
    assert leftovers == []
    assert p.read_text() == "a: 1\n"


